-- ============================================================
-- Explore With Me: основной сервис (ewm-main-service)
-- Синтаксис совместим с PostgreSQL 12+ и H2 2.x (MODE=PostgreSQL)
-- Скрипт идемпотентен (IF NOT EXISTS), можно запускать при каждом старте
-- (spring.sql.init.mode=always, spring.jpa.hibernate.ddl-auto=none)
-- ============================================================

-- ------------------------------------------------------------
-- Пользователи (Admin: Пользователи)
-- UserDto / NewUserRequest: name 2..250, email 6..254
-- Мин. длины проверяются в приложении (Bean Validation), в БД - максимумы и уникальность
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR(250) NOT NULL,
    email VARCHAR(254) NOT NULL,
    CONSTRAINT uq_users_email UNIQUE (email)
);

-- ------------------------------------------------------------
-- Категории (Admin/Public: Категории)
-- CategoryDto / NewCategoryDto: name 1..50, имя уникально (409)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS categories (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL,
    CONSTRAINT uq_categories_name UNIQUE (name)
);

-- ------------------------------------------------------------
-- События (Private/Admin/Public: События)
-- NewEventDto: title 3..120, annotation 20..2000, description 20..7000
-- state: PENDING (после создания) -> PUBLISHED | CANCELED
-- participant_limit: 0 = без ограничений
-- request_moderation: true - заявки подтверждает инициатор, false - автоподтверждение
-- confirmedRequests и views в таблице НЕ хранятся:
--   confirmedRequests = COUNT заявок со статусом CONFIRMED, views берутся из сервиса статистики
-- Удаление категории с событиями запрещено (RESTRICT -> 409 по спецификации)
-- Удаление пользователя удаляет его события (CASCADE)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS events (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title              VARCHAR(120)  NOT NULL,
    annotation         VARCHAR(2000) NOT NULL,
    description        VARCHAR(7000) NOT NULL,
    category_id        BIGINT        NOT NULL,
    initiator_id       BIGINT        NOT NULL,
    event_date         TIMESTAMP     NOT NULL,
    created_on         TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    published_on       TIMESTAMP,
    lat                DOUBLE PRECISION NOT NULL,
    lon                DOUBLE PRECISION NOT NULL,
    paid               BOOLEAN       NOT NULL DEFAULT FALSE,
    participant_limit  INTEGER       NOT NULL DEFAULT 0,
    request_moderation BOOLEAN       NOT NULL DEFAULT TRUE,
    state              VARCHAR(20)   NOT NULL DEFAULT 'PENDING',
    CONSTRAINT fk_events_category  FOREIGN KEY (category_id)  REFERENCES categories (id) ON DELETE RESTRICT,
    CONSTRAINT fk_events_initiator FOREIGN KEY (initiator_id) REFERENCES users (id)      ON DELETE CASCADE,
    CONSTRAINT chk_events_state CHECK (state IN ('PENDING', 'PUBLISHED', 'CANCELED')),
    CONSTRAINT chk_events_participant_limit CHECK (participant_limit >= 0)
);

-- ------------------------------------------------------------
-- Заявки на участие (Private: Запросы на участие)
-- status: PENDING | CONFIRMED | REJECTED | CANCELED
-- Одна заявка пользователя на событие (повтор -> 409)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS participation_requests (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id     BIGINT      NOT NULL,
    requester_id BIGINT      NOT NULL,
    created      TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status       VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    CONSTRAINT fk_requests_event     FOREIGN KEY (event_id)     REFERENCES events (id) ON DELETE CASCADE,
    CONSTRAINT fk_requests_requester FOREIGN KEY (requester_id) REFERENCES users (id)  ON DELETE CASCADE,
    CONSTRAINT uq_requests_event_requester UNIQUE (event_id, requester_id),
    CONSTRAINT chk_requests_status CHECK (status IN ('PENDING', 'CONFIRMED', 'REJECTED', 'CANCELED'))
);

-- ------------------------------------------------------------
-- Подборки событий (Admin/Public: Подборки событий)
-- NewCompilationDto: title 1..50, pinned по умолчанию false
-- Уникальность title - единственное нарушение целостности, которое может дать 409 при создании
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS compilations (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title  VARCHAR(50) NOT NULL,
    pinned BOOLEAN     NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_compilations_title UNIQUE (title)
);

-- Связь подборка <-> событие (многие ко многим); подборка может не содержать событий
-- Удаление подборки или события удаляет только связь, а не само событие/подборку
CREATE TABLE IF NOT EXISTS compilation_events (
    compilation_id BIGINT NOT NULL,
    event_id       BIGINT NOT NULL,
    CONSTRAINT pk_compilation_events PRIMARY KEY (compilation_id, event_id),
    CONSTRAINT fk_compevents_compilation FOREIGN KEY (compilation_id) REFERENCES compilations (id) ON DELETE CASCADE,
    CONSTRAINT fk_compevents_event       FOREIGN KEY (event_id)       REFERENCES events (id)       ON DELETE CASCADE
);

-- ------------------------------------------------------------
-- Комментарии к событиям (дополнительная фича)
-- Комментировать можно только опубликованные события (проверяется в приложении)
-- status: PENDING (новый или изменённый автором) -> APPROVED | REJECTED (решение админа)
-- При правке автором комментарий возвращается в PENDING, moderation_reason сбрасывается
-- Для REJECTED причина отклонения обязательна
-- Удаление события или автора удаляет его комментарии (CASCADE) - подтвердить командой
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS comments (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id          BIGINT        NOT NULL,
    author_id         BIGINT        NOT NULL,
    text              VARCHAR(2000) NOT NULL,
    status            VARCHAR(20)   NOT NULL DEFAULT 'PENDING',
    moderation_reason VARCHAR(500),
    created_on        TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_on        TIMESTAMP,
    moderated_on      TIMESTAMP,
    CONSTRAINT fk_comments_event  FOREIGN KEY (event_id)  REFERENCES events (id) ON DELETE CASCADE,
    CONSTRAINT fk_comments_author FOREIGN KEY (author_id) REFERENCES users (id)  ON DELETE CASCADE,
    CONSTRAINT chk_comments_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    CONSTRAINT chk_comments_reject_reason CHECK (status <> 'REJECTED' OR moderation_reason IS NOT NULL)
);

-- Лайки комментариев: один лайк на пару (комментарий, пользователь)
-- Запрет лайка собственного комментария и лайка не одобренного комментария проверяется в приложении
-- Счётчик лайков = COUNT по этой таблице, отдельно не хранится
CREATE TABLE IF NOT EXISTS comment_likes (
    comment_id BIGINT    NOT NULL,
    user_id    BIGINT    NOT NULL,
    created_on TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_comment_likes PRIMARY KEY (comment_id, user_id),
    CONSTRAINT fk_likes_comment FOREIGN KEY (comment_id) REFERENCES comments (id) ON DELETE CASCADE,
    CONSTRAINT fk_likes_user    FOREIGN KEY (user_id)    REFERENCES users (id)    ON DELETE CASCADE
);

-- ------------------------------------------------------------
-- Индексы под запросы API
-- ------------------------------------------------------------
-- Private: события пользователя; Admin: поиск по users
CREATE INDEX IF NOT EXISTS idx_events_initiator ON events (initiator_id);
-- Проверка "есть ли события в категории" при удалении; фильтр по categories
CREATE INDEX IF NOT EXISTS idx_events_category ON events (category_id);
-- Public/Admin: фильтры по state и диапазону event_date
CREATE INDEX IF NOT EXISTS idx_events_state_date ON events (state, event_date);
-- Подсчёт confirmedRequests и выборка заявок события
CREATE INDEX IF NOT EXISTS idx_requests_event_status ON participation_requests (event_id, status);
-- Private: заявки пользователя
CREATE INDEX IF NOT EXISTS idx_requests_requester ON participation_requests (requester_id);
-- Обратный поиск подборок по событию
CREATE INDEX IF NOT EXISTS idx_compevents_event ON compilation_events (event_id);
-- Public: фильтр pinned
CREATE INDEX IF NOT EXISTS idx_compilations_pinned ON compilations (pinned);
-- Комментарии: публичная выдача (событие + статус, по дате), комментарии автора
CREATE INDEX IF NOT EXISTS idx_comments_event_status ON comments (event_id, status, created_on);
CREATE INDEX IF NOT EXISTS idx_comments_author ON comments (author_id);
-- Лайки пользователя (проверка и снятие лайка; каскад при удалении пользователя)
CREATE INDEX IF NOT EXISTS idx_comment_likes_user ON comment_likes (user_id);
